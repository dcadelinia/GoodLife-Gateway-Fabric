from pydantic import BaseModel, Field
from typing import List, Optional

class BlackRockRiskMetrics(BaseModel):
    portfolio_insulation_score: float = Field(..., description="Erosion index under Aladdin templates")
    instant_treasury_yield_delta: float = Field(..., description="Instant yield optimization vector generated by grid correction")
    asset_liquidity_status: str = Field(..., description="Current state of hard commodities: STABLE, LOCKED, or DEPLOYED")

class PerplexityVerification(BaseModel):
    regulatory_citations: List[str] = Field(..., description="Live verification URLs validating trade legality or zoning parameters")
    policy_shift_detected: bool = Field(..., description="Flags if real-time web search detected localized legal anomalies")

class AmazonLogisticsManifest(BaseModel):
    fulfillment_routing_node: str = Field(..., description="Target regional micro-fulfillment center tracking node")
    fleet_throughput_efficiency: float = Field(..., description="Calculated supply chain density metric under hyperscale tracking")

class Gr00tPhysicalRobotPolicy(BaseModel):
    workflow_override: str = Field(..., description="Target module: GR00T_MOBILITY, GR00T_DEXTERITY, or GR00T_PERCEPTION")
    trajectory_node_path: List[str] = Field(..., description="Geospatial navigation paths for physical AI tracking")
    target_embodiment_id: str = Field(..., description="Unique hardware address of autonomous truck or drone unit")

class AnomalyCorrectionPayload(BaseModel):
    """
    Unified structural payload coordinating reasoning, capital defense, 
    live information retrieval, and robotic execution.
    """
    is_compliant: bool = Field(..., description="Must validate zoning laws and SOWEGA compliance parameters")
    target_action: str = Field(..., description="Action deployment: REDIRECT_FLEET, FLIP_HYDRO_VALVE, or LOCKDOWN_LOOP")
    optimized_routing_lane: List[str] = Field(..., description="Coordinate node arrays optimized for physical asset defense")
    narrative_alert_string: str = Field(..., description="Gamified lore telemetry string matching Veridyan and Last Living Leaf universes")
    
    capital_metrics: BlackRockRiskMetrics = Field(..., description="Aladdin-derived financial risk and yield tracking values")
    external_intel: PerplexityVerification = Field(..., description="Real-time web verified regulatory tracking data")
    supply_chain: AmazonLogisticsManifest = Field(..., description="Hyperscale distribution routing directives")
    gr00t_policy: Gr00tPhysicalRobotPolicy = Field(..., description="Direct physical AI instruction matrix passed to NVIDIA hardware")
